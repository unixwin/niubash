//! niubash#1057: on Windows the login marker (`--login`/`-l`, and the
//! argv[0] `-` seed) is accepted but INERT on the interactive startup
//! face — `run_startup_files` treats it exactly like no flag, so the
//! generated plugin loader -> ~/.niubashrc (`--rcfile` and
//! `NIU_RC_POLICY` apply unchanged) -> completion -> greeting sequence
//! runs. This restores the CHANGELOG's standing contract (since 1.4.0):
//! "Windows accepts the flags with unchanged behavior (no login
//! concept)". GNU shell.c:1833's "the login profile chain replaces the
//! interactive-RC alternative" is a deliberate product fork on this
//! face, not a GNU-alignment gap.
//!
//! What does NOT change on Windows: the non-interactive `-c` face keeps
//! the GNU login chain (niubash#399/#587/#602), and posix mode keeps it
//! on every platform (its documented contract is GNU-faithful user-file
//! selection). Every test here is Windows-only — the Unix contract is
//! pinned by issue590/issue603.

#![cfg(windows)]

use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

fn niu_binary() -> PathBuf {
    let p = PathBuf::from(env!("CARGO_BIN_EXE_niu"));
    if p.exists() {
        return p;
    }
    let mut fallback = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    fallback.push("target");
    fallback.push("debug");
    fallback.push(if cfg!(windows) { "niu.exe" } else { "niu" });
    fallback
}

const LOADER_PRELUDE: &str = "# niubash generated plugin loader — DO NOT EDIT (regenerated by `niu plugin` verbs).\n# schema: niubash:plugin-loader@1\n";

/// A home that stages every file the interactive face could touch:
/// the generated loader, `~/.niubashrc`, `~/.bash_profile`, and
/// `~/.bashrc` (the last only reachable through the opt-in
/// `NIU_RC_POLICY=bashrc-fallback`). Exactly one rc-family file may run
/// per invocation — the probes below pin which.
fn unique_home(label: &str) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let home = std::env::temp_dir().join(format!(
        "niu-issue1057-{label}-{}-{nanos}",
        std::process::id()
    ));
    std::fs::create_dir_all(home.join(".niubash").join("generated")).unwrap();
    std::fs::write(
        home.join(".niubash").join("generated").join("plugins.niu"),
        format!("{LOADER_PRELUDE}export LOADER_RAN=1\n"),
    )
    .unwrap();
    std::fs::write(home.join(".niubashrc"), "export RC_RAN=1\n").unwrap();
    std::fs::write(home.join(".bash_profile"), "export PROFILE_RAN=1\n").unwrap();
    std::fs::write(home.join(".bashrc"), "export BASHRC_RAN=1\n").unwrap();
    home
}

fn run_niu(home: &Path, args: &[&str], envs: &[(&str, &str)]) -> Output {
    let mut command = Command::new(niu_binary());
    command
        .args(args)
        .env_clear()
        .env("PATH", std::env::var("PATH").unwrap_or_default())
        .env("HOME", home)
        .env("USERPROFILE", home)
        .stdin(Stdio::null());
    for (name, value) in envs {
        command.env(name, value);
    }
    command.output().expect("spawn niu")
}

fn stdout_of(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

const PROBE: &str = "echo \"loader=${LOADER_RAN:-unset} rc=${RC_RAN:-unset} rcfile=${RCFILE_RAN:-unset} profile=${PROFILE_RAN:-unset} bashrc=${BASHRC_RAN:-unset}\"";

/// The shared assertion for the interactive login face: identical to
/// the non-login interactive row — loader, then the rc, and neither
/// the GNU profile chain nor `.bashrc`.
fn assert_interactive_login_reads_the_rc(stdout: &str) {
    assert!(
        stdout.contains("loader=1"),
        "login interactive must load the generated loader: {stdout}"
    );
    assert!(
        stdout.contains("rc=1"),
        "Windows login interactive must source ~/.niubashrc (#1057): {stdout}"
    );
    assert!(
        stdout.contains("profile=unset"),
        "Windows login interactive must skip the GNU profile chain (#1057): {stdout}"
    );
    assert!(
        stdout.contains("bashrc=unset"),
        "primary-only policy: ~/.bashrc stays unread on the interactive face: {stdout}"
    );
}

#[test]
fn windows_login_long_flag_reads_the_rc() {
    let home = unique_home("long-flag");
    let output = run_niu(&home, &["--login", "-i", "-c", PROBE], &[]);
    assert_interactive_login_reads_the_rc(&stdout_of(&output));
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn windows_login_short_flag_reads_the_rc() {
    let home = unique_home("short-flag");
    let output = run_niu(&home, &["-l", "-i", "-c", PROBE], &[]);
    assert_interactive_login_reads_the_rc(&stdout_of(&output));
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn windows_login_honors_rcfile() {
    let home = unique_home("rcfile");
    let rcfile = home.join("probe-rc");
    std::fs::write(&rcfile, "export RCFILE_RAN=1\n").unwrap();
    let rcfile_arg = rcfile.to_string_lossy().replace('\\', "/");
    // --rcfile must precede -c: everything after the command word is a
    // positional operand to it, not an option.
    let output = run_niu(
        &home,
        &["--login", "-i", "--rcfile", &rcfile_arg, "-c", PROBE],
        &[],
    );
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("loader=1"),
        "the generated loader still runs ahead of --rcfile: {stdout}"
    );
    assert!(
        stdout.contains("rcfile=1"),
        "--login -i --rcfile must source the explicit rc (#1057): {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "the default ~/.niubashrc stays unread when --rcfile wins: {stdout}"
    );
    assert!(
        stdout.contains("profile=unset"),
        "the GNU profile chain stays off the interactive face: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn windows_login_dash_c_keeps_the_gnu_chain() {
    // The guard against overreach: the NON-interactive `-c` face keeps
    // the GNU login chain on Windows (niubash#399/#587/#602).
    let home = unique_home("dash-c");
    let output = run_niu(
        &home,
        &[
            "-l",
            "-c",
            "echo \"profile=${PROFILE_RAN:-unset} rc=${RC_RAN:-unset}\"",
        ],
        &[],
    );
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("profile=1"),
        "-l -c must still source the GNU profile chain on Windows (#587): {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "the non-interactive face never reads the rc: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn windows_nonlogin_interactive_unchanged() {
    // Control: the non-login interactive face is byte-for-byte the same
    // funnel the login marker now shares.
    let home = unique_home("nonlogin");
    let output = run_niu(&home, &["-i", "-c", PROBE], &[]);
    assert_interactive_login_reads_the_rc(&stdout_of(&output));
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn windows_login_bashrc_fallback_policy_applies() {
    // NIU_RC_POLICY=bashrc-fallback makes ~/.bashrc eligible for the rc
    // slot only when ~/.niubashrc is genuinely absent — and the login
    // marker must not change that selection on Windows.
    let home = unique_home("bashrc-fallback");
    std::fs::remove_file(home.join(".niubashrc")).unwrap();
    let output = run_niu(
        &home,
        &["--login", "-i", "-c", PROBE],
        &[("NIU_RC_POLICY", "bashrc-fallback")],
    );
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("loader=1"),
        "the generated loader still runs under the fallback policy: {stdout}"
    );
    assert!(
        stdout.contains("bashrc=1"),
        "NIU_RC_POLICY=bashrc-fallback must select ~/.bashrc under --login -i (#1057): {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "the absent ~/.niubashrc stays absent: {stdout}"
    );
    assert!(
        stdout.contains("profile=unset"),
        "the GNU profile chain stays off the interactive face: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}
