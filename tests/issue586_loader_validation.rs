//! niubash#586: the generated plugin loader must pass the same
//! validate() gate at startup that the publish path applies — a foreign
//! or truncated file at ~/.niubash/generated/plugins.niu is never
//! sourced on the strength of its filename alone (loader.rs loading
//! contract). Validation failure and unreadable loaders produce one
//! stderr diagnostic (path + regeneration verb) and the shell stays
//! usable; the doctor reports warn, not ok.

use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

fn niu_binary() -> PathBuf {
    let p = PathBuf::from(env!("CARGO_BIN_EXE_niu"));
    if p.exists() {
        return p;
    }
    let mut fallback = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    fallback.push("target");
    fallback.push("debug");
    fallback.push(if cfg!(windows) { "niu.exe" } else { "niu" });
    fallback
}

fn unique_home(label: &str) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let home = std::env::temp_dir().join(format!(
        "niu-issue586-{label}-{}-{nanos}",
        std::process::id()
    ));
    std::fs::create_dir_all(home.join(".niubash").join("generated")).unwrap();
    std::fs::write(home.join(".niubashrc"), "export RC_RAN=1\n").unwrap();
    home
}

fn write_loader(home: &Path, bytes: &[u8]) {
    std::fs::write(
        home.join(".niubash").join("generated").join("plugins.niu"),
        bytes,
    )
    .unwrap();
}

fn run_niu(home: &Path, args: &[&str]) -> Output {
    Command::new(niu_binary())
        .args(args)
        .env_clear()
        .env("PATH", std::env::var("PATH").unwrap_or_default())
        .env("HOME", home)
        .env("USERPROFILE", home)
        .stdin(Stdio::null())
        .output()
        .expect("spawn niu")
}

fn stdout_of(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn stderr_of(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

const PROBE: &str =
    "echo \"LOADER_FOREIGN=${LOADER_FOREIGN:-unset} LOADER_RAN=${LOADER_RAN:-unset} RC_RAN=${RC_RAN:-unset}\"";

#[test]
fn foreign_loader_is_refused_with_a_diagnostic() {
    let home = unique_home("foreign");
    // No banner, no schema — a foreign file in the generated directory.
    write_loader(&home, b"export LOADER_FOREIGN=executed\necho loader-ran\n");
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    let stderr = stderr_of(&output);
    assert!(output.status.success(), "shell must stay usable: {stderr}");
    assert!(
        stdout.contains("LOADER_FOREIGN=unset"),
        "foreign loader must not execute: {stdout}"
    );
    assert!(
        !stdout.contains("loader-ran"),
        "foreign loader output leaked: {stdout}"
    );
    // The rc still loads (startup continues without the loader).
    assert!(stdout.contains("RC_RAN=1"), "rc must still load: {stdout}");
    assert!(
        stderr.contains("failed validation") && stderr.contains("niu plugin sync"),
        "expected a validation diagnostic with the regeneration verb: {stderr}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn truncated_loader_is_refused() {
    let home = unique_home("truncated");
    // Schema line present but the banner destroyed (truncated write).
    write_loader(
        &home,
        b"# schema: niubash:plugin-loader@1\nexport LOADER_RAN=1\n",
    );
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("LOADER_RAN=unset"),
        "truncated loader must not execute: {stdout}"
    );
    assert!(stderr_of(&output).contains("failed validation"));
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn valid_loader_loads_without_a_warning() {
    let home = unique_home("valid");
    write_loader(
        &home,
        b"# niubash generated plugin loader \xe2\x80\x94 DO NOT EDIT (regenerated by `niu plugin` verbs).\n\
          # schema: niubash:plugin-loader@1\n\
          export LOADER_RAN=1\n",
    );
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("LOADER_RAN=1"),
        "valid loader must load: {stdout}"
    );
    assert!(
        !stderr_of(&output).contains("failed validation"),
        "valid loader must not warn: {}",
        stderr_of(&output)
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn unreadable_loader_is_diagnosed_not_silent() {
    let home = unique_home("unreadable");
    // Invalid UTF-8: read_loader_text folds this into the same None as
    // a missing file; startup must still diagnose it.
    write_loader(&home, &[0xff, 0xfe, 0x00, 0x41, 0x80, 0x81]);
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    assert!(output.status.success());
    assert!(
        stderr_of(&output).contains("could not be read as text"),
        "expected an unreadable-loader diagnostic: {}",
        stderr_of(&output)
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn doctor_warns_on_an_invalid_loader() {
    let home = unique_home("doctor");
    write_loader(&home, b"export LOADER_FOREIGN=executed\n");
    let output = run_niu(&home, &["doctor"]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("plugin loader") && stdout.contains("failed validation"),
        "doctor must warn on a loader startup refuses: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}
