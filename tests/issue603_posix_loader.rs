//! niubash#603: the generated plugin loader loads for POSIX interactive
//! shells too — posix mode governs the choice and order of USER files
//! (profile chain, then `$ENV`), not whether niu's own activation plane
//! loads (the #590 defect class). The slot mirrors the ordinary branch's
//! relative order:
//!
//! | shell            | expected sequence        |
//! |------------------|--------------------------|
//! | login posix      | profile -> loader -> ENV |
//! | non-login posix  | loader -> ENV            |
//! | login ordinary   | profile -> loader (#590) |
//! | non-login ord.   | loader -> rc (#359)      |
//!
//! Each startup file appends its letter to `$ORDER`, so one probe string
//! asserts both that the loader ran and where it ran.

use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

fn niu_binary() -> PathBuf {
    let p = PathBuf::from(env!("CARGO_BIN_EXE_niu"));
    if p.exists() {
        return p;
    }
    let mut fallback = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    fallback.push("target");
    fallback.push("debug");
    fallback.push(if cfg!(windows) { "niu.exe" } else { "niu" });
    fallback
}

const LOADER_PRELUDE: &str = "# niubash generated plugin loader \u{2014} DO NOT EDIT (regenerated by `niu plugin` verbs).\n# schema: niubash:plugin-loader@1\n";

fn unique_home(label: &str, loader_body: &str) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let home = std::env::temp_dir().join(format!(
        "niu-issue603-{label}-{}-{nanos}",
        std::process::id()
    ));
    std::fs::create_dir_all(home.join(".niubash").join("generated")).unwrap();
    std::fs::write(
        home.join(".niubash").join("generated").join("plugins.niu"),
        format!("{LOADER_PRELUDE}{loader_body}"),
    )
    .unwrap();
    std::fs::write(
        home.join(".niubashrc"),
        "export ORDER=\"${ORDER}R\"\nexport RC_RAN=1\n",
    )
    .unwrap();
    std::fs::write(
        home.join(".bash_profile"),
        "export ORDER=\"${ORDER}P\"\nexport PROFILE_RAN=1\n",
    )
    .unwrap();
    std::fs::write(
        home.join("posix.env"),
        "export ORDER=\"${ORDER}E\"\nexport ENV_RAN=1\necho ran > \"$HOME/env-ran.txt\"\n",
    )
    .unwrap();
    home
}

fn run_niu(home: &Path, args: &[&str]) -> Output {
    let env_file = home.join("posix.env");
    Command::new(niu_binary())
        .args(args)
        .env_clear()
        .env("PATH", std::env::var("PATH").unwrap_or_default())
        .env("HOME", home)
        .env("USERPROFILE", home)
        .env("ENV", env_file)
        .stdin(Stdio::null())
        .output()
        .expect("spawn niu")
}

fn stdout_of(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

const PROBE: &str = "echo \"order=${ORDER:-none} rc=${RC_RAN:-unset} profile=${PROFILE_RAN:-unset} env=${ENV_RAN:-unset}\"";

const LOADER_BODY: &str = "export ORDER=\"${ORDER}L\"\nexport LOADER_RAN=1\n";

#[test]
fn login_posix_loads_loader_between_profile_and_env() {
    let home = unique_home("login-posix", LOADER_BODY);
    let output = run_niu(&home, &["--posix", "-l", "-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("order=PLE"),
        "login posix: profile -> loader -> $ENV: {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "posix mode never sources the rc: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn non_login_posix_loads_loader_before_env() {
    let home = unique_home("nonlogin-posix", LOADER_BODY);
    let output = run_niu(&home, &["--posix", "-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("order=LE"),
        "non-login posix: loader -> $ENV (the loader sits before the \
         posix rc face, as it sits before the rc on the ordinary \
         branch): {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "posix mode never sources the rc: {stdout}"
    );
    assert!(
        stdout.contains("profile=unset"),
        "non-login shells skip the profile chain: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn login_ordinary_keeps_the_590_order() {
    let home = unique_home("login-ordinary", LOADER_BODY);
    let output = run_niu(&home, &["-l", "-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("order=PL"),
        "login ordinary: profile -> loader, rc skipped (#590): {stdout}"
    );
    assert!(
        stdout.contains("env=unset"),
        "ordinary mode never sources $ENV: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn non_login_ordinary_keeps_loader_before_rc() {
    let home = unique_home("nonlogin-ordinary", LOADER_BODY);
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("order=LR"),
        "non-login ordinary: loader -> rc (#359): {stdout}"
    );
    assert!(
        stdout.contains("env=unset"),
        "ordinary mode never sources $ENV: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn login_posix_loader_exit_unwinds_before_env() {
    let home = unique_home("login-posix-exit", "export LOADER_RAN=1\nexit 7\n");
    let output = run_niu(
        &home,
        &["--posix", "-l", "-i", "-c", "echo SHOULD-NOT-RUN"],
    );
    let stdout = stdout_of(&output);
    assert_eq!(
        output.status.code(),
        Some(7),
        "an exit in the loader ends the invocation with its status: {stdout}"
    );
    assert!(
        !stdout.contains("SHOULD-NOT-RUN"),
        "the command must not run after a loader exit: {stdout}"
    );
    assert!(
        !home.join("env-ran.txt").exists(),
        "$ENV must not run after a loader exit"
    );
    let _ = std::fs::remove_dir_all(&home);
}
