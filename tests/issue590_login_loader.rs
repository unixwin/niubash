//! niubash#590: an interactive LOGIN shell loads the generated plugin
//! loader after the profile chain — the loader is niu's own activation
//! plane, not part of the GNU rc exchange, and the docs state no login
//! exception. The rc itself stays skipped on login shells (GNU parity:
//! a login shell reads the profile, not the rc).

use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

fn niu_binary() -> PathBuf {
    let p = PathBuf::from(env!("CARGO_BIN_EXE_niu"));
    if p.exists() {
        return p;
    }
    let mut fallback = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    fallback.push("target");
    fallback.push("debug");
    fallback.push(if cfg!(windows) { "niu.exe" } else { "niu" });
    fallback
}

const LOADER_PRELUDE: &str = "# niubash generated plugin loader \u{2014} DO NOT EDIT (regenerated by `niu plugin` verbs).\n# schema: niubash:plugin-loader@1\n";

fn unique_home(label: &str, loader_body: &str) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let home = std::env::temp_dir().join(format!(
        "niu-issue590-{label}-{}-{nanos}",
        std::process::id()
    ));
    std::fs::create_dir_all(home.join(".niubash").join("generated")).unwrap();
    std::fs::write(
        home.join(".niubash").join("generated").join("plugins.niu"),
        format!("{LOADER_PRELUDE}{loader_body}"),
    )
    .unwrap();
    std::fs::write(home.join(".niubashrc"), "export RC_RAN=1\n").unwrap();
    std::fs::write(home.join(".bash_profile"), "export PROFILE_RAN=1\n").unwrap();
    home
}

fn run_niu(home: &Path, args: &[&str]) -> Output {
    Command::new(niu_binary())
        .args(args)
        .env_clear()
        .env("PATH", std::env::var("PATH").unwrap_or_default())
        .env("HOME", home)
        .env("USERPROFILE", home)
        .stdin(Stdio::null())
        .output()
        .expect("spawn niu")
}

fn stdout_of(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

const PROBE: &str =
    "echo \"loader=${LOADER_RAN:-unset} rc=${RC_RAN:-unset} profile=${PROFILE_RAN:-unset}\"";

#[test]
fn login_interactive_loads_the_loader_but_not_the_rc() {
    let home = unique_home("login", "export LOADER_RAN=1\n");
    let output = run_niu(&home, &["-l", "-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(
        stdout.contains("loader=1"),
        "login interactive must load the loader: {stdout}"
    );
    assert!(
        stdout.contains("rc=unset"),
        "login shells still skip the rc (GNU parity): {stdout}"
    );
    assert!(
        stdout.contains("profile=1"),
        "login shells still source the profile: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn non_login_interactive_keeps_loading_loader_and_rc() {
    let home = unique_home("nonlogin", "export LOADER_RAN=1\n");
    let output = run_niu(&home, &["-i", "-c", PROBE]);
    let stdout = stdout_of(&output);
    assert!(stdout.contains("loader=1"), "{stdout}");
    assert!(stdout.contains("rc=1"), "{stdout}");
    assert!(stdout.contains("profile=unset"), "{stdout}");
    let _ = std::fs::remove_dir_all(&home);
}

#[test]
fn login_loader_exit_unwinds_the_invocation() {
    let home = unique_home("exit", "export LOADER_RAN=1\nexit 7\n");
    let output = run_niu(&home, &["-l", "-i", "-c", "echo SHOULD-NOT-RUN"]);
    let stdout = stdout_of(&output);
    assert_eq!(
        output.status.code(),
        Some(7),
        "an exit in the loader ends the invocation with its status: {stdout}"
    );
    assert!(
        !stdout.contains("SHOULD-NOT-RUN"),
        "the command must not run after a loader exit: {stdout}"
    );
    let _ = std::fs::remove_dir_all(&home);
}
