#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES.md from Cargo.lock -- one line per crate.
//
// Honesty contract (do not weaken): Cargo.lock records package NAME, VERSION
// and SOURCE only -- it does NOT carry each crate's license field. This
// generator therefore emits an inventory (name + version + source class),
// not license texts. Full license texts live in each crate's source
// distribution (docs.rs / the crate's repository). To bundle SPDX IDs and
// license texts automatically, wire `cargo about` or `cargo deny` -- that is
// the deliberate upgrade path, not a missing feature of this script.
//
// Usage: node scripts/gen-third-party-notices.mjs [path/to/Cargo.lock]
//        (defaults to the repo root lockfile relative to this script)
// Writes THIRD-PARTY-NOTICES.md next to the lockfile. Keep the generated
// file out of commits; regenerate for reference when Cargo.lock changes.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const lockPath = resolve(
  process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "Cargo.lock"),
);
const outPath = join(dirname(lockPath), "THIRD-PARTY-NOTICES.md");

const lock = readFileSync(lockPath, "utf8");

// Minimal targeted parse of Cargo.lock's [[package]] blocks. The lockfile is
// generated TOML with a flat shape (name/version/source/checksum/
// dependencies), so line-scoped extraction is sufficient and dependency-free.
const packages = [];
let current = null;
for (const rawLine of lock.split(/\r?\n/)) {
  const line = rawLine.trim();
  if (line === "[[package]]") {
    current = { name: undefined, version: undefined, source: undefined };
    packages.push(current);
    continue;
  }
  if (!current) continue;
  const m = /^(name|version|source)\s*=\s*"(.*)"$/.exec(line);
  if (m) current[m[1]] = m[2];
}

const valid = packages.filter((p) => p.name && p.version);
const cratesIo = valid
  .filter((p) => p.source?.startsWith("registry+"))
  .sort((a, b) => a.name.localeCompare(b.name));
const other = valid
  .filter((p) => !p.source?.startsWith("registry+"))
  .sort((a, b) => a.name.localeCompare(b.name));
const dropped = packages.length - valid.length;

const lines = [];
lines.push("# Third-party notices (Rust dependency inventory)");
lines.push("");
lines.push(
  `Generated by \`scripts/gen-third-party-notices.mjs\` from \`Cargo.lock\` (${valid.length} packages` +
    `${dropped ? `, ${dropped} malformed entries skipped` : ""}).`,
);
lines.push("");
lines.push(
  "> Cargo.lock does not record per-crate license fields, so this file is an",
  "> inventory, not a license bundle: one line per crate (name + version).",
  "> Each crate's complete license text is available in its source",
  "> distribution (see <https://docs.rs/> or the crate's repository). To",
  "> generate SPDX identifiers and vendored license texts, wire `cargo about`",
  "> or `cargo deny` -- not yet part of this repository's toolchain.",
);
lines.push("");
lines.push(`## crates.io crates (${cratesIo.length})`);
lines.push("");
for (const p of cratesIo) lines.push(`- ${p.name} ${p.version}`);
lines.push("");
if (other.length > 0) {
  lines.push(`## Non-registry packages (${other.length})`);
  lines.push("");
  lines.push(
    "No `source` entry in Cargo.lock: workspace members and path dependencies --",
    "first-party code, not third-party payloads.",
  );
  lines.push("");
  for (const p of other) lines.push(`- ${p.name} ${p.version}`);
  lines.push("");
}

writeFileSync(outPath, lines.join("\n").replace(/\n*$/, "\n"), "utf8");
console.log(
  `wrote ${outPath}: ${valid.length} packages (${cratesIo.length} crates.io, ${other.length} non-registry)`,
);
